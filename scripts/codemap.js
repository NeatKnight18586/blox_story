// scripts/codemap.js — generates CODEMAP.md: one line per .js/.json file under engine/, avatar-style/, parts/, scripts/, beasts/, cast/ (first comment line).
import {readdirSync, readFileSync, statSync, writeFileSync, existsSync} from 'node:fs';
import path from 'node:path';
const DIRS = ['engine', 'avatar-style', 'parts', 'scripts', 'beasts', 'cast'], out = [];
const walk = d => { for (const f of readdirSync(d).sort()) { const p = path.join(d, f), s = statSync(p);
  if (s.isDirectory()) { if (f !== 'node_modules' && f !== 'build') walk(p); } else if (/\.(js|json)$/.test(f)) out.push(p); } };
for (const d of DIRS) if (existsSync(d)) walk(d);
const header = p => { const t = readFileSync(p, 'utf8').split('\n', 40);
  if (p.endsWith('.json')) { const m = t.join('\n').match(/"(?:note|_note|comment|description)"\s*:\s*"((?:[^"\\]|\\.)*)"/); return m ? m[1].slice(0, 140) : '(no header)'; }
  for (const l of t) { const s = l.trim(); if (!s || s.startsWith('#!')) continue; const m = s.match(/^(?:\/\/+|\/\*+|\*)\s*(.+?)\s*(?:\*\/)?$/); return m ? m[1].replace(/^\S+\.(js|json)\s+[—-]\s+/, '').slice(0, 140) : '(no header)'; }
  return '(no header)'; };
writeFileSync('CODEMAP.md', '# CODEMAP — generated by `npm run codemap`; one line per file (first comment line)\n' + out.map(p => `${p} — ${header(p)}`).join('\n') + '\n');
console.log(`CODEMAP.md: ${out.length} files`);
