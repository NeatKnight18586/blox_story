def conv(c,cxs,cys,dx):
    kind=c['kind']; p=list(c['params']); x0,y0=c['x0'],c['y0']
    X=lambda x:R((x+x0-cxs)/CW+dx); Y=lambda y:R(-(y+y0-cys)/CH)
    L=lambda v:R(v/CW)
    pts=lambda q:[v for i in range(0,len(q),2) for v in (X(q[i]),Y(q[i+1]))]
    if kind=='seg': return [['s',L(p[4])]+pts(p[:4])]
    if kind=='taper': return [['t',0,X(p[0]),Y(p[1]),L(p[2]),X(p[3]),Y(p[4]),L(p[5])]]
    if kind=='curve': return [['c',L(p[8])]+pts(p[:8])]
    if kind.startswith('poly'): k=(len(p)-1)//2; return [['p',L(p[-1])]+pts(p[:2*k])]
    if kind=='ring': return [['r',L(p[4]),X(p[0]),Y(p[1]),L(p[2]),L(p[3])]]
    if kind in('dshape','dome'):
        s=max(0,p[5]) if len(p)==6 else 0; w=p[4]
