    if kind=='discholes':
        out=['o',0,X(p[0]),Y(p[1]),L(p[2]),L(p[3])]
        for k in range(4,len(p),4): out+= [X(p[k]),Y(p[k+3]),X(p[k+2]),Y(p[k+1])]
        return [out]
    if kind=='heart2': return [['h',0,X(p[0]),Y(p[1]),L(p[2]),L(p[3]),Y(p[4])]]
    if kind in('dropline','dropfill'):
        w=L(p[5]) if kind=='dropline' else 0; return [['d',w,X(p[0]),Y(p[1]),X(p[2]),Y(p[3]),L(p[4])]]
    if kind=='star': return [['*',L(p[5]),X(p[0]),Y(p[1]),L(p[2]),L(p[3]),R(p[4])]]
    if kind=='tongue': w=L(p[16]*.9); return [['c',w]+pts(p[:8]),['D',w,X(p[8]),Y(p[9]),L(p[10]),L(p[11]),0],['s',L(p[16]*.9)]+pts(p[12:16])]
