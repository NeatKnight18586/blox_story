#!/usr/bin/env python3
"""tools/variety_matrix.py: R-ALGO-04 variety matrix (Retention Engine Phase 2).

  python3 tools/variety_matrix.py [--dir episodes] [--out docs/VARIETY_MATRIX.md] [--check]

Reads every <dir>/EP*/spec.yml, orders them by (season, episode), and writes a Markdown table of the variety axes.
An episode is flagged when any axis repeats one of the previous 3 episodes. --check: exit 1 if any flag.
Pure helpers (axes, variety_flags, render) are unit-tested in tests/v2/test_spec.py.
"""
import argparse, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WINDOW = 3
# axis name → how to read it from a spec (all compared case/space-insensitively)
AXES = {
    'hook_type': lambda s: s.get('hook_type'),
    'counter_type': lambda s: (s.get('counter') or {}).get('type'),
    'twist_category': lambda s: s.get('twist_category'),
    'setting_era': lambda s: s.get('setting_era'),
    'ending_type': lambda s: s.get('payoff_type'),
}


def norm(v):
    return ' '.join(str(v).lower().replace('_', ' ').split()) if v is not None else None


def axes(spec):
    return {k: norm(f(spec)) for k, f in AXES.items()}


def order_key(spec):
    return (int(spec.get('season') or 0), int(spec.get('episode') or 0), str(spec.get('id', '')))


def variety_flags(spec, earlier):
    """spec vs the specs before it (any order; the last WINDOW by order_key count). → ['R-ALGO-04: hook_type …', …]"""
    prev = sorted((e for e in earlier if order_key(e) < order_key(spec)), key=order_key)[-WINDOW:]
    me, out = axes(spec), []
    for k, v in me.items():
        hits = [e.get('id', '?') for e in prev if v is not None and axes(e)[k] == v]
        if hits: out.append(f"R-ALGO-04: {k} '{v}' repeats {', '.join(hits)} (previous {WINDOW})")
    return out


def render(specs):
    specs = sorted(specs, key=order_key)
    head = ['episode', 'slug', *AXES, 'flags']
    rows = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    flagged = 0
    for i, s in enumerate(specs):
        f = variety_flags(s, specs[:i]); flagged += bool(f)
        a = axes(s)
        rows.append('| ' + ' | '.join([f"{s.get('id', '?')} (S{s.get('season')}E{s.get('episode')})", str(s.get('slug', '')),
                                       *[a[k] or '—' for k in AXES], '; '.join(x.split(': ', 1)[1] for x in f) or 'ok']) + ' |')
    text = ('# Variety matrix (generated by tools/variety_matrix.py; do not edit)\n\n'
            f'R-ALGO-04: an episode may not repeat any axis of the previous {WINDOW} episodes. Episodes flagged: {flagged}.\n\n'
            + '\n'.join(rows) + '\n')
    return text, flagged


def load_specs(d):
    import yaml
    return [yaml.safe_load(p.read_text()) or {} for p in sorted(Path(d).glob('EP*/spec.yml'))]


def main():
    a = argparse.ArgumentParser()
    a.add_argument('--dir', default=str(ROOT / 'episodes')); a.add_argument('--out', default=str(ROOT / 'docs/VARIETY_MATRIX.md'))
    a.add_argument('--check', action='store_true'); o = a.parse_args()
    text, flagged = render(load_specs(o.dir))
    Path(o.out).write_text(text); print(f'{o.out}: {flagged} flagged')
    sys.exit(1 if o.check and flagged else 0)


if __name__ == '__main__':
    main()
