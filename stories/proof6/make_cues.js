// node stories/proof6/make_cues.js: synthetic cues.json for the P5 proof reel (no voice; D3 untouched). Every BEATS row's VO words sit
// 0.3 s apart from the row's cue start, so each cut and each *marked* word is a word onset.
import {readFileSync, writeFileSync} from 'node:fs';
import {parseBrief} from '../../scripts/v2/brief2spec.js';
const rows = parseBrief(readFileSync('stories/proof6/BRIEF.md', 'utf8')).rows;
const lines = rows.map((r, i) => {
  const t0 = Number(r.cue.split(/[–—-]/)[0]), ws = r.vo.replace(/\*/g, '').split(/\s+/), words = ws.map((w, k) => ({w, start: +(t0 + .3 * k).toFixed(2), end: +(t0 + .3 * k + .28).toFixed(2)}));
  return {line: i + 1, text: ws.join(' '), start: words[0].start, end: words.at(-1).end, words};
});
writeFileSync('stories/proof6/cues.json', JSON.stringify({story: 'proof6', note: 'SYNTHETIC placeholder cues for the P5 proof reel: no voice; 0.3 s per word. Generated by make_cues.js.', duration: +(Number(rows.at(-1).cue.split(/[–—-]/)[1]) - .85).toFixed(2), lines}, null, 1) + '\n');
console.log('cues.json:', lines.length, 'lines');
